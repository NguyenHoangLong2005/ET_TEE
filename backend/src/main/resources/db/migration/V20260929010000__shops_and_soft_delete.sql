-- ------------------------------------------------------------
-- 2. Khoa ngoai tu cac bang mang shop_id ve shops(id)
-- ------------------------------------------------------------
-- Da kiem tra CHI DOC: moi bang duoi day chi co gia tri shop_id trong {1, 2}
-- hoac NULL, nen an toan them FK ngay. NULL van hop le (vd: users khong thuoc
-- chi nhanh nao nhu ADMIN/khach hang) - khong dat NOT NULL o day.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_shop') THEN
        ALTER TABLE users ADD CONSTRAINT fk_users_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_orders_shop') THEN
        ALTER TABLE orders ADD CONSTRAINT fk_orders_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_inventories_shop') THEN
        ALTER TABLE inventories ADD CONSTRAINT fk_inventories_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_vouchers_shop') THEN
        ALTER TABLE vouchers ADD CONSTRAINT fk_vouchers_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_support_tickets_shop') THEN
        ALTER TABLE support_tickets ADD CONSTRAINT fk_support_tickets_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_shop_work_shifts_shop') THEN
        ALTER TABLE shop_work_shifts ADD CONSTRAINT fk_shop_work_shifts_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_cskh_voucher_quotas_shop') THEN
        ALTER TABLE cskh_voucher_quotas ADD CONSTRAINT fk_cskh_voucher_quotas_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_cskh_voucher_grants_shop') THEN
        ALTER TABLE cskh_voucher_grants ADD CONSTRAINT fk_cskh_voucher_grants_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_shop_product_configs_shop') THEN
        ALTER TABLE shop_product_configs ADD CONSTRAINT fk_shop_product_configs_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_staff_performance_evaluations_shop') THEN
        ALTER TABLE staff_performance_evaluations ADD CONSTRAINT fk_staff_performance_evaluations_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_store_featured_categories_shop') THEN
        ALTER TABLE store_featured_categories ADD CONSTRAINT fk_store_featured_categories_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
    -- suppliers.shop_id duoc them o phan 4 ben duoi, FK khai bao cung mot cho o do.
END $$;


-- ------------------------------------------------------------
-- 3a. Xoa mem + audit cho categories
-- ------------------------------------------------------------
ALTER TABLE categories ADD COLUMN IF NOT EXISTS created_at TIMESTAMP;
ALTER TABLE categories ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP;
ALTER TABLE categories ADD COLUMN IF NOT EXISTS created_by VARCHAR(255);
ALTER TABLE categories ADD COLUMN IF NOT EXISTS updated_by VARCHAR(255);
ALTER TABLE categories ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP;

UPDATE categories SET created_at = COALESCE(created_at, CURRENT_TIMESTAMP) WHERE created_at IS NULL;

-- Cac rang buoc unique cu tren categories chong cheo nhau (mot vai constraint
-- la du thua tu cac lan Hibernate ddl-auto=update khac nhau; xem doi chieu
-- trong bao cao khao sat). Bo het, thay bang 2 UNIQUE INDEX PARTIAL chi tinh
-- ban ghi con song, de mot ten/slug da bi xoa co the dung lai duoc.
ALTER TABLE categories DROP CONSTRAINT IF EXISTS uk_cat_name_parent;
ALTER TABLE categories DROP CONSTRAINT IF EXISTS uk_cat_slug;
ALTER TABLE categories DROP CONSTRAINT IF EXISTS ukoul14ho7bctbefv8jywp5v3i2; -- trung voi uk_cat_slug
ALTER TABLE categories DROP CONSTRAINT IF EXISTS ukt8o6pivur7nn124jehx7cygw5; -- UNIQUE(name) don le, sai pham vi so voi (name, parent_id) hien tai

CREATE UNIQUE INDEX IF NOT EXISTS uk_cat_slug_active ON categories(slug) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_cat_name_parent_active ON categories(name, parent_id) WHERE deleted_at IS NULL;


