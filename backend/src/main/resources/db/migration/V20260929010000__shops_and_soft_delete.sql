DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_suppliers_shop') THEN
        ALTER TABLE suppliers ADD CONSTRAINT fk_suppliers_shop FOREIGN KEY (shop_id) REFERENCES shops(id);
    END IF;
END $$;

