-- ------------------------------------------------------------
-- 1. Bang shops
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS shops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(500),
    phone VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

-- Chi nhanh 1: chi nhanh chinh dang hoat dong. Dia chi de NULL, sua trong
-- trang admin sau (theo yeu cau). Chi nhanh 2: du lieu thu nghiem, danh dau
-- is_active=false nhung KHONG xoa - cac don hang/nhan vien dang tham chieu
-- shop_id=2 van con nguyen, chi khong con hien la chi nhanh dang hoat dong.
